'use strict';
const assert = require('assert');
const {CODES, fromResults, combineOr} = require('./equipment');
assert.deepStrictEqual(CODES.slice(), ['248','710','4NB','536','453','454','4HA','494']);
const options = Object.fromEntries(CODES.map(code=>[code,false]));
let detected=fromResults(options);
assert.deepStrictEqual(Object.values(detected),Array(8).fill(false));
detected=fromResults({...options,'248':true,'710':true,'4NB':true,'536':true,'453':true,'454':true,'4HA':true});
assert.deepStrictEqual(Object.values(detected),Array(8).fill(true));
detected=fromResults({...options,'494':true});
assert.strictEqual(detected.frontSeatHeating,true);
assert.strictEqual(detected.rearSeatHeating,false);
detected=fromResults(null);
assert.ok(Object.values(detected).every(value=>value==='unknown'));
detected=fromResults({'494':true});
assert.strictEqual(detected.frontSeatHeating,true);
assert.strictEqual(detected.rearSeatHeating,'unknown');
assert.strictEqual(combineOr(false,'unknown'),'unknown');
assert.strictEqual(combineOr(true,'unknown'),true);
console.log('Climate Comfort shared equipment and unknown handling OK');
