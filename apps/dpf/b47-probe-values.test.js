'use strict';
const assert = require('assert');
const {candidate} = require('./b47-probe-values');
const checks = [
    [0x44BE, [0x62,0x44,0xBE,0x06,0x7D], '25.35 g'],
    [0x44BD, [0x62,0x44,0xBD,0x07,0x3B], '28.24 g'],
    [0x44BF, [0x62,0x44,0xBF,0x00,0x06,0xCB,0xC4], '445.38 km'],
    [0x44C7, [0x62,0x44,0xC7,0x02,0x41], '577 km']
];
for(const [did,uds,expected] of checks){
    const decoded=candidate(did,uds);
    assert.ok(decoded);
    assert.strictEqual(decoded.display,expected);
    assert.ok(decoded.note);
}
// Do not invent values for uncertain DIDs or negative/mismatched responses.
assert.strictEqual(candidate(0x44ED,[0x62,0x44,0xED,0x55,0xED]),null);
assert.strictEqual(candidate(0x4502,[0x62,0x45,0x02,0x22,0x23]),null);
assert.strictEqual(candidate(0x44BE,[0x7F,0x22,0x31]),null);
assert.strictEqual(candidate(0x44BE,[0x62,0x44,0xBD,0x06,0x7D]),null);
assert.strictEqual(candidate(0x44BE,[0x62,0x44,0xBE,0x06]),null);
console.log('B47 candidate values: verified against tester raw replies');
